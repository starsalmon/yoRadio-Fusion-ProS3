#!/usr/bin/env python3
"""Rasterise images_src/bluetooth_220px.png into RGB565 + alpha for the ProS3
BT RX station-logo slot (64x64 and 80x80 slots, same arrays/macros as the
older SVG generator, so display.cpp is unchanged).

The PNG is cropped to its opaque bounding box, scaled to the slot height
(width follows aspect, centred horizontally by buildBtRxStationLogo), with
premultiplied-alpha LANCZOS so edges blend against the theme background.

Outputs: src/displays/bitmaps/bt_official_logo_data.h
Requires: pillow
"""
from __future__ import annotations
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "images_src" / "bluetooth_220px.png"
OUT_H = ROOT / "src/displays/bitmaps/bt_official_logo_data.h"
SLOT_HEIGHTS = (64, 80)


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def raster(img, h):
    w = max(1, min(h, int(round(h * img.width / img.height))))
    out = img.convert("RGBa").resize((w, h), Image.Resampling.LANCZOS).convert("RGBA")
    rgb, a = [], []
    for y in range(h):
        for x in range(w):
            r, g, b, al = out.getpixel((x, y))
            if al < 8:
                al = 0
            rgb.append(rgb565(r, g, b) if al else 0)
            a.append(al)
    return w, rgb, a


def arr(t, name, vals, per):
    lines = [", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f"static const {t} {name}[] = {{\n  " + ",\n  ".join(lines) + ",\n};\n"


def main():
    img = Image.open(SRC).convert("RGBA")
    img = img.crop(img.getchannel("A").getbbox())
    parts = ["/* Auto-generated by tools/gen_bt_rx_station_logo_png.py — do not edit. */",
             "#pragma once", "#include <stdint.h>",
             f"/* Source: images_src/{SRC.name} (cropped {img.width}x{img.height}) */", ""]
    for h in SLOT_HEIGHTS:
        w, rgb, a = raster(img, h)
        parts += [f"#define BT_OFFICIAL_LOGO_W_{h} {w}", f"#define BT_OFFICIAL_LOGO_H_{h} {h}",
                  arr("uint16_t", f"bt_official_logo_rgb_{h}", rgb, 12),
                  arr("uint8_t", f"bt_official_logo_a_{h}", a, 16), ""]
        print(f"{h}: {w}x{h}")
    OUT_H.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print("Wrote", OUT_H)


if __name__ == "__main__":
    main()
